export function normalizeRtoCode(value) {
  const trimmed = String(value || '').trim().toUpperCase().replace(/\s+/g, '')
  if (!trimmed) return ''
  const match = trimmed.match(/^([A-Z]{2})-?(\d{1,2})$/)
  if (!match) return trimmed
  return `${match[1]}-${match[2].padStart(2, '0')}`
}

/** Map stored value to the canonical list name (case-insensitive). */
export function normalizeIndianState(value) {
  const trimmed = String(value || '').trim()
  if (!trimmed) return ''
  return INDIAN_STATES.find((name) => name.toLowerCase() === trimmed.toLowerCase()) || trimmed
}
